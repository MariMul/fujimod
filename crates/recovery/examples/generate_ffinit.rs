//! Generate the loader template from the guest sources, with no camera data.
//! FFINIT_CC and FFINIT_LD select GNU GCC 4.6.4 and GNU ld.
use object::{Object, ObjectSection, ObjectSymbol};
use std::{env, fs, path::PathBuf, process::Command};

fn run(program: &str, args: &[&str], work: &std::path::Path) {
    let output = Command::new(program)
        .args(args)
        .current_dir(work)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
}
fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let work = root.join("../../target/recovery-template");
    fs::create_dir_all(&work).unwrap();
    for name in ["loader.c", "entry.S", "ffinit.h"] {
        fs::copy(root.join("guest").join(name), work.join(name)).unwrap();
    }
    // Declaration order is part of the stable loader layout. Firmware data is
    // inserted by the Rust builder, after linking this four-byte placeholder.
    fs::write(
        work.join("bindings.c"),
        r#"
#include "ffinit.h"
const ff_u8 ffinit_boot_header[2048] = {0};
const ff_u8 ffinit_setup_data[4] = {0};
const ff_u32 ffinit_crc_table[256] = {0};
const struct ffinit_config ffinit_config = {0,0,0,0,0,0,0,0,ffinit_setup_data};
"#,
    )
    .unwrap();
    let cc = env::var("FFINIT_CC").expect("set FFINIT_CC to GCC 4.6.4");
    let version = Command::new(&cc).arg("-dumpversion").output().unwrap();
    assert_eq!(String::from_utf8_lossy(&version.stdout).trim(), "4.6.4");
    for (source, output) in [
        ("bindings.c", "bindings.o"),
        ("loader.c", "loader.o"),
        ("entry.S", "entry.o"),
    ] {
        run(
            &cc,
            &[
                "-marm",
                "-march=armv7-a",
                "-mfloat-abi=soft",
                "-fno-common",
                "-ffunction-sections",
                "-fno-asynchronous-unwind-tables",
                "-fdata-sections",
                "-O1",
                "-fno-omit-frame-pointer",
                "-O2",
                "-fomit-frame-pointer",
                "-mcpu=cortex-a9",
                "-fno-builtin",
                "-ffreestanding",
                "-fno-delete-null-pointer-checks",
                "-c",
                source,
                "-o",
                output,
            ],
            &work,
        );
    }
    fs::write(
        work.join("loader.ld"),
        r#"
ENTRY(ffinit_entry)
SECTIONS {
 .text 0x104000 : { KEEP(*(.text .text.*)) }
 .rodata : { KEEP(*(.rodata .rodata.*)) }
 .data : { *(.data .data.*) }
 .bss : { *(.bss .bss.* COMMON) }
 /DISCARD/ : { *(.comment) *(.note.GNU-stack) *(.ARM.attributes) *(.ARM.exidx*) *(.ARM.extab*) }
}
PROVIDE(ffinit_stock_resume = 0x100004);
PROVIDE(ffinit_stack_top = 0x11d000);
"#,
    )
    .unwrap();
    run(
        &env::var("FFINIT_LD").expect("set FFINIT_LD"),
        &[
            "-T",
            "loader.ld",
            "--gc-sections",
            "--emit-relocs",
            "-o",
            "loader.elf",
            "bindings.o",
            "loader.o",
            "entry.o",
        ],
        &work,
    );
    let bytes = fs::read(work.join("loader.elf")).unwrap();
    let elf = object::File::parse(bytes.as_slice()).unwrap();
    let symbols: std::collections::BTreeMap<_, _> = elf
        .symbols()
        .filter_map(|s| Some((s.name().ok()?.to_string(), s.address())))
        .collect();
    let text = elf.section_by_name(".text").unwrap();
    let rodata = elf.section_by_name(".rodata").unwrap();
    let data_at = symbols["ffinit_setup_data"];
    let suffix_at = data_at + 4;
    let suffix = &rodata.data().unwrap()[(suffix_at - rodata.address()) as usize..];
    let mut out = String::from(
        "// Generated by cargo run -p fujimod-recovery --example generate_ffinit.\n// Contains only the guest loader compiled from guest/, with empty data placeholders.\n",
    );
    for (name, value) in &symbols {
        if name.starts_with("ffinit_")
            && !["ffinit_stock_resume", "ffinit_stack_top"].contains(&name.as_str())
        {
            out += &format!(
                "pub const {}: usize = {:#x};\n",
                name.to_uppercase(),
                value - 0x104000
            );
        }
    }
    for (name, data) in [("TEXT", text.data().unwrap()), ("SUFFIX", suffix)] {
        out += &format!("pub const {name}: &[u8] = &[\n");
        for row in data.chunks(20) {
            out += "    ";
            for b in row {
                out += &format!("{b},");
            }
            out += "\n";
        }
        out += "];\n";
    }
    out += "// (text offset, ARM relocation type, target offset or external identity).\npub const FIXUPS: &[(usize, u32, i64)] = &[\n";
    for (offset, rel) in text.relocations() {
        let offset = offset - text.address();
        let object::RelocationFlags::Elf { r_type } = rel.flags() else {
            panic!("ELF relocation expected")
        };
        if ![2, 43, 44].contains(&r_type) {
            assert!([28, 29].contains(&r_type));
            continue;
        }
        let object::RelocationTarget::Symbol(index) = rel.target() else {
            panic!("symbol expected")
        };
        let symbol = elf.symbol_by_index(index).unwrap();
        let name = symbol.name().unwrap();
        let word = u32::from_le_bytes(
            text.data().unwrap()[offset as usize..offset as usize + 4]
                .try_into()
                .unwrap(),
        );
        let target = match name {
            "ffinit_stack_top" => -1,
            "ffinit_stock_resume" => -2,
            _ if r_type == 2 => i64::from(word) - 0x104000,
            _ => {
                // MOVW/MOVT reference the zero-initialized progress anchor.
                assert_eq!(symbol.address(), symbols["ffinit_progress"]);
                (symbol.address() - 0x104000) as i64
            }
        };
        out += &format!("    ({offset:#x}, {r_type}, {target}),\n");
    }
    out += "];\n";
    let target = root.join("src/ffinit.generated.rs");
    if env::args().any(|a| a == "--check") {
        assert_eq!(fs::read_to_string(target).unwrap(), out);
    } else {
        let temporary = target.with_extension(format!("rs.{}.tmp", std::process::id()));
        fs::write(&temporary, out).unwrap();
        if let Err(error) = fs::rename(&temporary, target) {
            let _ = fs::remove_file(temporary);
            panic!("Cannot install generated template: {error}");
        }
    }
}
