//! Compile the ROM-file firmware reader, with no camera input bytes.
use object::{Object, ObjectSection, ObjectSymbol};
use std::{env, fs, path::PathBuf, process::Command};
fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let work = root.join("../../target/lupi-firmware-template");
    fs::create_dir_all(&work).unwrap();
    let cc = env::var("LUPI_CC").expect("set LUPI_CC to GCC 4.6.4");
    let ld = env::var("LUPI_LD").expect("set LUPI_LD");
    let version = Command::new(&cc).arg("-dumpversion").output().unwrap();
    assert_eq!(String::from_utf8_lossy(&version.stdout).trim(), "4.6.4");
    let source = root.join("guest/lupi/firmware.c");
    let compiled = Command::new(cc)
        .args([
            "-std=gnu99",
            "-marm",
            "-mcpu=cortex-r4",
            "-mfloat-abi=soft",
            "-Os",
            "-ffreestanding",
            "-fno-builtin",
            "-fno-common",
            "-fno-unwind-tables",
            "-fno-asynchronous-unwind-tables",
            "-c",
        ])
        .arg(source)
        .args(["-o", "firmware.o"])
        .current_dir(&work)
        .output()
        .unwrap();
    assert!(
        compiled.status.success(),
        "{}",
        String::from_utf8_lossy(&compiled.stderr)
    );
    fs::write(
        work.join("firmware.ld"),
        r#"
ENTRY(lupi_firmware_indexed)
SECTIONS {
 .program 0x2000 : {
  *(.text .text.*) *(.rodata .rodata.*) *(.data .data.*)
  . = ALIGN(4); lupi_firmware_config = .; LONG(0); LONG(0); LONG(0); LONG(0); LONG(0);
  *(.bss .bss.*) *(COMMON)
  . = ALIGN(4);
 }
 /DISCARD/ : { *(.comment) *(.note*) *(.ARM.attributes) *(.ARM.exidx*) *(.ARM.extab*) }
}
ASSERT(ADDR(.program) + SIZEOF(.program) <= 0x3000, "Lupi reader exceeds loader reservation")
"#,
    )
    .unwrap();
    let linked = Command::new(ld)
        .args([
            "-T",
            "firmware.ld",
            "--no-undefined",
            "-o",
            "firmware.elf",
            "firmware.o",
        ])
        .current_dir(&work)
        .output()
        .unwrap();
    assert!(
        linked.status.success(),
        "{}",
        String::from_utf8_lossy(&linked.stderr)
    );
    let bytes = fs::read(work.join("firmware.elf")).unwrap();
    let elf = object::File::parse(bytes.as_slice()).unwrap();
    let program = elf.section_by_name(".program").unwrap().data().unwrap();
    let mut text = String::from(
        "// Generated by cargo run -p fujimod-recovery --example generate_lupi_firmware.\n// Compiled C with empty configuration; no camera input bytes.\n",
    );
    for name in [
        "lupi_firmware_config",
        "lupi_firmware_indexed",
        "lupi_firmware_indexed4",
        "lupi_firmware_indexed3",
    ] {
        let address = elf
            .symbols()
            .find(|s| s.name().ok() == Some(name))
            .unwrap()
            .address();
        text += &format!("pub const {}: usize = {address:#x};\n", name.to_uppercase());
    }
    text += "pub const PROGRAM: &[u8] = &[\n";
    for row in program.chunks(20) {
        text += "    ";
        for byte in row {
            text += &format!("{byte},");
        }
        text.push('\n');
    }
    text += "];\n";
    let path = root.join("src/lupi_firmware.generated.rs");
    if env::args().any(|a| a == "--check") {
        assert_eq!(fs::read_to_string(path).unwrap(), text);
    } else {
        fs::write(path, text).unwrap();
    }
}
