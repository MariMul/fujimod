//! Compile the small ROM-assisted loader without any camera input bytes.
use object::{Object, ObjectSection, ObjectSymbol};
use std::{
    env, fs,
    path::{Path, PathBuf},
    process::Command,
};
// Keep the guest beyond the ROM filesystem's complete workspace, including
// its 512-byte sector buffer at 0xfff00248. Reserve the upper 4 KiB for calls.
const SRAM: u64 = 0xfff00800;
fn run(program: &str, args: &[&str], cwd: &Path) {
    let r = Command::new(program)
        .args(args)
        .current_dir(cwd)
        .output()
        .unwrap();
    assert!(r.status.success(), "{}", String::from_utf8_lossy(&r.stderr));
}
fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let work = root.join("../../target/lupi-template");
    fs::create_dir_all(&work).unwrap();
    let cc = env::var("LUPI_CC").expect("set LUPI_CC to GCC 4.6.4");
    let v = Command::new(&cc).arg("-dumpversion").output().unwrap();
    assert_eq!(String::from_utf8_lossy(&v.stdout).trim(), "4.6.4");
    for name in ["loader.c", "entry.S"] {
        fs::copy(root.join("guest/lupi").join(name), work.join(name)).unwrap();
        run(
            &cc,
            &[
                "-std=gnu99",
                "-marm",
                "-mcpu=cortex-r4",
                "-mfloat-abi=soft",
                "-Os",
                "-ffreestanding",
                "-fno-builtin",
                "-fno-common",
                "-fno-unwind-tables",
                "-fno-asynchronous-unwind-tables",
                "-c",
                name,
                "-o",
                &format!("{name}.o"),
            ],
            &work,
        );
    }
    fs::write(
        work.join("loader.ld"),
        format!(
            r#"
ENTRY(lupi_entry)
SECTIONS {{
 .start 0 : {{ *(.start) }}
 lupi_source = SIZEOF(.start);
 lupi_sram = {SRAM:#x};
 .guest lupi_sram : AT(lupi_source) {{
  *(.text .text.*) *(.rodata .rodata.*)
  . = ALIGN(4); lupi_config = .; LONG(0); LONG(0); LONG(0); LONG(0); LONG(0);
  . = ALIGN(4);
 }}
 lupi_length = SIZEOF(.guest);
 /DISCARD/ : {{ *(.comment) *(.note*) *(.ARM.attributes) *(.ARM.exidx*) *(.ARM.extab*) }}
}}
ASSERT(lupi_sram >= 0xfff00448, "Lupi guest overlaps ROM filesystem workspace")
ASSERT(lupi_sram + SIZEOF(.guest) <= 0xfff01000, "Lupi guest overlaps ROM call stack")
"#
        ),
    )
    .unwrap();
    run(
        &env::var("LUPI_LD").expect("set LUPI_LD"),
        &[
            "-T",
            "loader.ld",
            "--no-undefined",
            "-o",
            "loader.elf",
            "entry.S.o",
            "loader.c.o",
        ],
        &work,
    );
    let bytes = fs::read(work.join("loader.elf")).unwrap();
    let elf = object::File::parse(bytes.as_slice()).unwrap();
    let mut binary = vec![];
    for name in [".start", ".guest"] {
        binary.extend_from_slice(elf.section_by_name(name).unwrap().data().unwrap());
    }
    let config = elf
        .symbols()
        .find(|s| s.name().ok() == Some("lupi_config"))
        .unwrap()
        .address()
        - SRAM;
    let config = config + elf.section_by_name(".start").unwrap().size();
    let mut text = format!(
        "// Generated by cargo run -p fujimod-recovery --example generate_lupi.\n// Compiled guest code with empty configuration; no ROM or update bytes.\npub const CONFIG: usize = {config:#x};\npub const BYTES: &[u8] = &[\n"
    );
    for row in binary.chunks(20) {
        text.push_str("    ");
        for byte in row {
            text += &format!("{byte},");
        }
        text.push('\n');
    }
    text += "];\n";
    let path = root.join("src/lupi.generated.rs");
    if env::args().any(|a| a == "--check") {
        assert_eq!(fs::read_to_string(path).unwrap(), text);
    } else {
        fs::write(path, text).unwrap();
    }
}
