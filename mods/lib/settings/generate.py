#!/usr/bin/env python3
"""Run the pinned upstream JSON Schema-to-C generator; no camera dependencies.

This is a build integration, not another schema compiler. Schema references,
types, defaults and parsers are generated by upstream. Its qualification
limits are documented in README.md before these parsers replace live settings.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys


COMPONENT = Path(__file__).resolve().parent
UPSTREAM = COMPONENT / 'upstream'
GENERATOR_REVISION = '570075656a080a6756add4dc209d8f8d5ed4c0da'
JSMN_REVISION = '85695f3d5903b1cd5b4030efe50db3b4f5f3c928'


class GenerationError(ValueError):
    pass


def checked_revision(directory, expected):
    try:
        actual = subprocess.check_output(
            ['git', '-C', str(directory), 'rev-parse', 'HEAD'], text=True).strip()
        dirty = subprocess.check_output(
            ['git', '-C', str(directory), 'status', '--porcelain', '--untracked-files=no'],
            text=True).strip()
    except (OSError, subprocess.CalledProcessError) as error:
        raise GenerationError('Initialize the settings generator submodules recursively') from error
    if actual != expected or dirty:
        raise GenerationError(f'{directory.name}: expected clean revision {expected}; got {actual}')


def generate(schema, output, *, authorized_paths=()):
    """Generate section.c/.h and provenance into the caller's build directory."""
    checked_revision(UPSTREAM, GENERATOR_REVISION)
    checked_revision(UPSTREAM / 'jsmn', JSMN_REVISION)
    schema, output = Path(schema).resolve(), Path(output).resolve()
    authorized_paths = tuple(Path(path).resolve() for path in authorized_paths)
    if output == COMPONENT or output.is_relative_to(UPSTREAM):
        raise GenerationError('Generated output must not replace component or upstream sources')
    output.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, str(UPSTREAM / 'json_schema_to_c.py'), str(schema),
               str(output / 'section.c'), str(output / 'section.h')]
    if authorized_paths:
        command.extend(['--authorized-paths', *map(str, authorized_paths)])
    result = subprocess.run(command, text=True, capture_output=True)
    if result.returncode:
        raise GenerationError(result.stderr.strip() or result.stdout.strip())
    # Include exact inputs, including local schema references, as reported by
    # the upstream loader. Run in a separate process to avoid its module cache
    # retaining a previously loaded schema between builds.
    inventory = '''
import hashlib, json, pathlib, sys
from js2c.schema import load_schema, SCHEMA_CACHE
source = pathlib.Path(sys.argv[1])
load_schema(str(source), [str(source.parent), *sys.argv[2:]])
paths = sorted({str(source), *SCHEMA_CACHE})
print(json.dumps({p: hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest() for p in paths}))
'''
    inputs = subprocess.check_output(
        [sys.executable, '-c', inventory, str(schema), *map(str, authorized_paths)],
        cwd=UPSTREAM, text=True)
    metadata = dict(generator_revision=GENERATOR_REVISION, jsmn_revision=JSMN_REVISION,
                    schemas=json.loads(inputs), outputs={
                        name: hashlib.sha256((output / name).read_bytes()).hexdigest()
                        for name in ('section.c', 'section.h')})
    (output / 'generation.json').write_text(json.dumps(metadata, indent=2)+'\n')
    return metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('schema', type=Path)
    parser.add_argument('--out', required=True, type=Path)
    parser.add_argument('--authorized-path', action='append', default=[], type=Path)
    args = parser.parse_args()
    try:
        generate(args.schema, args.out, authorized_paths=args.authorized_path)
    except (GenerationError, OSError) as error:
        parser.exit(1, f'{error}\n')


if __name__ == '__main__':
    main()
